HELP_TEXT = '''📖 Как пользоваться ботом

Это личный блокнот с календарём. Вы записываете дела, встречи и планы, а бот хранит их и при желании напоминает. Ваши записи и группы видны только вам.

① СОЗДАТЬ ЗАМЕТКУ
В главном меню нажмите «＋ Создать заметку» и напишите, что нужно запомнить. Например: «Встреча — обсудить документы».
Затем укажите дату одним из двух способов:
• Календарь: стрелками выберите месяц и нажмите число. После этого напишите время, например 14:30.
• «Ввести дату и время»: отправьте всё сразу, например 31.12.2026 14:30. Удобно для далёких дат.
Проверьте карточку и нажмите «Сохранить». До сохранения запись — черновик. Дата и время должны быть в будущем.

② ПРИКРЕПИТЬ ФОТО ИЛИ ФАЙЛ
Это необязательно. После текста заметки, на этапе выбора даты или времени, отправьте фото, документ, видео, аудио или другое медиа. Нажмите «Продолжить», чтобы закончить создание.
Можно добавить вложения и позже: откройте карточку → «Прикрепить» → отправьте файлы → «Готово».
Кнопка «Вложения» показывает список: нажмите нужный файл, и бот пришлёт его в чат. До 20 вложений на заметку.

③ ПОСМОТРЕТЬ ЗАПИСИ
«📋 Текущие записи» — будущие записи по дате и времени. Нажмите кнопку с датой, чтобы открыть карточку. Длинные списки можно листать; переходы обновляют сообщение.

④ ИЗМЕНИТЬ ИЛИ УДАЛИТЬ
В карточке нажмите «Текст» и отправьте новый текст целиком. «Дата и время» переносит запись. После переноса старое напоминание выключается — настройте его заново.
«Удалить» просит подтверждение. Вместе с записью удаляются её вложения из блокнота и отменяется напоминание. Исходные сообщения в чате остаются.

⑤ НАПОМИНАНИЯ
Сохранение заметки само по себе не включает уведомление. В карточке нажмите «Напоминание»: за 15 минут, час, день, в момент записи или «Своё время».
«Своё время» — точная дата и время, когда прислать уведомление, например 30.12.2026 18:00. Это может быть раньше самого дела.
«Выключить» в карточке отменяет уведомление только этой записи.
Общий выключатель в главном меню ставит все напоминания на паузу, сохраняя настройки. После включения прошедшие уведомления не присылаются. Все даты и время — по Москве.

⑥ ГРУППЫ
«📂 Группы» → «Создать группу» → напишите название, например «Работа» или «Личное».
В карточке сохранённой заметки нажмите «Изменить группу» и выберите папку. Без выбора заметка остаётся в «Без группы».
Откройте группу, чтобы увидеть все её заметки, включая прошлые. Там же можно изменить название или удалить группу. Удаление группы сохраняет записи, вложения и напоминания: заметки перейдут в «Без группы».

↩️ Если передумали, нажмите «Отмена» или отправьте /cancel. /start открывает главное меню, /help — эту инструкцию.

Важно: напоминания приходят, пока бот запущен на компьютере или сервере. Не блокируйте бота, если ждёте уведомления.'''
